#!/usr/bin/env node
'use strict';
// Generate renderer/tokens.css from assets/design/tokens.json, the ECHOCAT
// design system's token file (a copy of potacat-app/docs/design-system/
// tokens.json — test/design-tokens-test.js fails when the two drift).
// Plan: docs/design-system-plan.md, audit: docs/design-audit.md.
//
// What it writes, all prefixed --ds- so nothing collides with the existing
// desktop palette (styles.css :root / [data-theme] / [data-wcag] blocks):
//   - one [data-ds="<theme column>"] block per theme with every colour role,
//     aliases resolved to literals; :root carries the default theme
//     (POTACAT Dark = the "night" column, the phone's dark default);
//   - :root space / radius / size / stroke / opacity, and shadows per theme;
//   - type: --ds-font-sans / --ds-font-mono / --ds-font-body, --ds-font-scale,
//     and one .ds-<style> class per type style, sized calc(scale * px);
//   - Acid Burn's mono face (a theme trait on the phone, theme.ts) as
//     --ds-font-body: var(--ds-font-mono) inside its block.
// Run: node scripts/gen-design-tokens-css.js   (the test checks it is current)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'assets', 'design', 'tokens.json');
const OUT = path.join(ROOT, 'renderer', 'tokens.css');

// The phone's picker: theme id -> token column. Same ids on both apps.
const THEMES = [
  { id: 'potacat-dark', column: 'night', scheme: 'dark', name: 'POTACAT Dark' },
  { id: 'midnight', column: 'dark', scheme: 'dark', name: 'Midnight' },
  { id: 'acid-burn', column: 'acid', scheme: 'dark', name: 'Acid Burn', font: 'mono' },
  { id: 'potacat-light', column: 'light', scheme: 'light', name: 'POTACAT Light' },
];
const DEFAULT_COLUMN = 'night';
// Digits that line up in a column (the phone's generator marks the same four).
const TABULAR = new Set(['row-value', 'numeric-header', 'numeric-mark', 'numeric-dial']);
// Windows pins the mono face (the handoff: never rely on a fallback chain).
const MONO_DESKTOP = 'ui-monospace, Consolas, "Cascadia Mono", Menlo, "Roboto Mono", monospace';
const SANS_DESKTOP = 'system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';

function load(file) { return JSON.parse(fs.readFileSync(file || SRC, 'utf8')); }

function makeResolver(t) {
  const themes = t.color.themes.map((x) => x.id);
  const byName = new Map(t.color.tokens.map((x) => [x.name, x]));
  const raw = (tok, th) => (typeof tok.value === 'string' ? tok.value : (tok.value[th] != null ? tok.value[th] : tok.value[themes[0]]));
  return function resolve(name, th) {
    const tok = byName.get(name);
    if (!tok) throw new Error('unknown colour token ' + name);
    let v = raw(tok, th);
    for (let i = 0; typeof v === 'string' && v.startsWith('{') && i < 16; i++) v = raw(byName.get(v.slice(1, -1)), th);
    return v;
  };
}

/** Every theme column's colours, resolved: { column: { token: literal } }. */
function resolvedColors(t) {
  const resolve = makeResolver(t);
  const out = {};
  for (const th of t.color.themes.map((x) => x.id)) {
    out[th] = {};
    for (const tok of t.color.tokens) out[th][tok.name] = resolve(tok.name, th);
  }
  return out;
}

function shadowFor(tok, column, scheme) {
  if (typeof tok.value === 'string') return tok.value;
  if (tok.value[column] != null) return tok.value[column];
  // The file names light / dark / halloween; a theme without its own value
  // takes its scheme's (dark themes are flat).
  return scheme === 'light' ? tok.value.light : (tok.value.dark != null ? tok.value.dark : 'none');
}

function generate(t) {
  const colors = resolvedColors(t);
  const L = [];
  L.push('/*');
  L.push(' * POTACAT design tokens. GENERATED by scripts/gen-design-tokens-css.js');
  L.push(' * from assets/design/tokens.json (the ECHOCAT design system). Do not edit');
  L.push(' * by hand: change the token file and regenerate.');
  L.push(' *');
  L.push(' * Themes (data-ds on <html>): ' + THEMES.map((x) => `${x.column} = ${x.name} (${x.id})`).join(', ') + '.');
  L.push(' * :root carries the default, POTACAT Dark.');
  L.push(' */');
  L.push('');

  // Fixed families: one :root block.
  const fixed = [];
  const lengths = (family) => {
    for (const x of t[family].tokens) fixed.push(`  --ds-${x.name}: ${x.value};`);
  };
  lengths('spacing'); lengths('radius'); lengths('size'); lengths('stroke');
  if (t.icon && Array.isArray(t.icon.tokens)) lengths('icon');
  for (const x of t.opacity.tokens) fixed.push(`  --ds-${x.name}: ${x.value};`);
  fixed.push(`  --ds-font-sans: ${SANS_DESKTOP};`);
  fixed.push(`  --ds-font-mono: ${MONO_DESKTOP};`);
  fixed.push('  --ds-font-body: var(--ds-font-sans);');
  fixed.push('  --ds-font-scale: 1;');

  const themeBlock = (column, scheme, font, withScheme = true) => {
    const b = [];
    for (const tok of t.color.tokens) b.push(`  --ds-${tok.name}: ${colors[column][tok.name]};`);
    for (const tok of t.shadow.tokens) b.push(`  --ds-${tok.name}: ${shadowFor(tok, column, scheme)};`);
    if (font === 'mono') b.push('  --ds-font-body: var(--ds-font-mono);');
    // :root never sets color-scheme: the classic desktop themes own it until
    // a data-ds theme is chosen (a dark scheme on :root would turn the
    // classic light theme's form controls dark).
    if (withScheme) b.push(`  color-scheme: ${scheme};`);
    return b;
  };

  const def = THEMES.find((x) => x.column === DEFAULT_COLUMN);
  L.push(':root {');
  L.push(...fixed);
  L.push(...themeBlock(def.column, def.scheme, def.font, false));
  L.push('}');
  L.push('');
  for (const th of THEMES) {
    L.push(`[data-ds="${th.column}"] {`);
    L.push(...themeBlock(th.column, th.scheme, th.font));
    L.push('}');
    L.push('');
  }
  // Columns in the file that are not in the picker (Halloween) still get a
  // block, so a seasonal skin can be switched on with one attribute.
  for (const col of t.color.themes.map((x) => x.id)) {
    if (THEMES.some((x) => x.column === col)) continue;
    L.push(`[data-ds="${col}"] {`);
    L.push(...themeBlock(col, 'dark'));
    L.push('}');
    L.push('');
  }

  // Type styles.
  L.push('/* Type styles: one class each. Sizes scale with --ds-font-scale; a chrome');
  L.push('   region pins it (.ds-chrome) so fixed bars never burst. */');
  L.push('.ds-chrome { --ds-font-scale: 1; }');
  for (const g of t.type.groups) {
    for (const st of g.styles) {
      const fam = g.family === 'mono' ? 'var(--ds-font-mono)' : 'var(--ds-font-body)';
      const parts = [
        `font-family: ${fam}`,
        `font-size: calc(var(--ds-font-scale) * ${st.fontSize})`,
        `line-height: calc(var(--ds-font-scale) * ${st.lineHeight})`,
        `font-weight: ${st.fontWeight}`,
      ];
      if (st.letterSpacing) parts.push(`letter-spacing: ${st.letterSpacing}`);
      if (TABULAR.has(st.name)) parts.push('font-variant-numeric: tabular-nums');
      if (st.name === 'eyebrow' || st.name === 'eyebrow-strip' || st.name === 'tag') parts.push('text-transform: uppercase');
      L.push(`.ds-${st.name} { ${parts.join('; ')}; }`);
    }
  }
  L.push('');
  return L.join('\n');
}

module.exports = { THEMES, DEFAULT_COLUMN, load, resolvedColors, generate, SRC, OUT };

if (require.main === module) {
  const css = generate(load());
  fs.writeFileSync(OUT, css);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${load().color.tokens.length} colours x ${load().color.themes.length} themes`);
}
